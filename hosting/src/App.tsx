function formatReportDate(reportDate?: string, period?: string): string | undefined {
  if (!reportDate) return period;
  const parsed = new Date(reportDate);
  if (Number.isNaN(parsed.getTime())) return period || reportDate;
  return `Run ${parsed.toLocaleDateString(undefined, { day: 'numeric', month: 'short', year: 'numeric' })}`;
}

function buildFallbackBriefing(data: RegionData, totalOpportunities?: number): string {
  const allDeals = data.risks || [];
  const flagged = allDeals.filter(r => r.level === 'HIGH' || r.level === 'MEDIUM');
  const high = flagged.filter(r => r.level === 'HIGH').length;
  const medium = flagged.filter(r => r.level === 'MEDIUM').length;
  const regions = flagged.reduce<Record<string, number>>((acc, r) => {
    acc[r.region || 'Unknown'] = (acc[r.region || 'Unknown'] || 0) + 1;
    return acc;
  }, {});
  const topRegion = Object.entries(regions).sort((a, b) => b[1] - a[1])[0];
  const topRisk = flagged[0];
  const total = totalOpportunities ?? Number.parseInt(data.stats.pipeline.value, 10) ?? allDeals.length;

  if (!flagged.length) {
    return `${total} open opportunities were analysed and no high-priority risk cluster was detected in the current report. Forecast confidence and CRO recommendations are still being generated by the enrichment pass.`;
  }

  return `${total} open opportunities were analysed; ${flagged.length} are currently flagged by the risk engine, including ${high} high-priority deals and ${medium} medium-priority deals. Risk is most concentrated in ${topRegion?.[0] || 'the active pipeline'} (${topRegion?.[1] || flagged.length} flagged deals), with the top immediate intervention being ${topRisk?.value || 'the highest-risk active deal'}: ${topRisk?.summary || 'review required'}. The detailed AI briefing is still being enriched, but the base signal is already clear: leadership should inspect the highest-risk deals before relying on the current forecast.`;
}

