function dataAsOfLabel(reportDate?: string, period?: string): string | undefined {
  if (!reportDate) return period;
  const formatted = formatDate(reportDate);
  // formatDate hands back unparseable input unchanged; only label a real date.
  if (formatted === reportDate) return period || reportDate;
  return `Data as of ${formatted}`;
}

function buildFallbackBriefing(data: RegionData, totalOpportunities?: number): string {
  const allDeals = data.risks || [];
  const flagged = allDeals.filter(r => r.level === 'HIGH' || r.level === 'MEDIUM');
  const high = flagged.filter(r => r.level === 'HIGH').length;
  const medium = flagged.filter(r => r.level === 'MEDIUM').length;
  const regions = flagged.reduce<Record<string, number>>((acc, r) => {
    const label = regionLabel(r.region);
    acc[label] = (acc[label] || 0) + 1;
    return acc;
  }, {});
  const topRegion = Object.entries(regions).sort((a, b) => b[1] - a[1])[0];
  const topRisk = flagged[0];
  // parseInt gives NaN, not undefined, for a value like "$40K", so `??` alone would never reach the deal count.
  const total = [totalOpportunities, Number.parseInt(data.stats.pipeline.value, 10), allDeals.length]
    .find((n): n is number => typeof n === 'number' && Number.isFinite(n)) ?? allDeals.length;

  if (!flagged.length) {
    return `${total} open opportunities were analysed and no high-priority risk cluster was detected in the current report. Forecast confidence and CRO recommendations are still being generated by the enrichment pass.`;
  }

  return `${total} open opportunities were analysed; ${flagged.length} are currently flagged by the risk engine, including ${high} high-priority deals and ${medium} medium-priority deals. Risk is most concentrated in ${topRegion?.[0] || 'the active pipeline'} (${topRegion?.[1] || flagged.length} flagged deals), with the top immediate intervention being ${topRisk?.value || 'the highest-risk active deal'}: ${topRisk?.summary || 'review required'}. The detailed AI briefing is still being enriched, but the base signal is already clear: leadership should inspect the highest-risk deals before relying on the current forecast.`;
}

const visuallyHidden: React.CSSProperties = {
  position: 'absolute', width: 1, height: 1, padding: 0, margin: -1,
  overflow: 'hidden', clip: 'rect(0 0 0 0)', whiteSpace: 'nowrap', border: 0,
};

export default function App() {
  const { view, selectTab, selectRegion, setFilters, goToDeals } = useDashboardView();
  const reviews = useSharedReviews();
  const {
    data, allData, loading, isLive, showingContent, executiveBriefing, totalOpportunities, reportPeriod,
    reportDate, reportCreatedAt, regionCounts, dealsError, reportMeta, twentyQuestions,
    competitiveDisplacement, deltaIntelligence,
  } = useRegion(view.region);
  const [uploadOpen, setUploadOpen] = useState(false);

  // Every tab reads the same region-filtered deals: one region control, no disagreement.
  const regionDeals = useMemo(() => inRegion(allData.risks ?? [], view.region), [allData, view.region]);
  // Portfolio-wide like the LLM briefing it stands in for: the Overview labels it global under a region filter.
  const fallbackBriefing = isLive && !executiveBriefing ? buildFallbackBriefing(allData, totalOpportunities) : undefined;
  const dataAsOf = dataAsOfLabel(reportDate, reportPeriod);
  const nextRefresh = formatDate(nextScheduledRun(new Date()).toISOString());
  const tabLabel = TABS.find(t => t.key === view.tab)?.label ?? 'Overview';
  const panelRef = useRef<HTMLDivElement>(null);

  // Picking a tab (or a click-through into one) from far down the page starts the new tab at its top,
  // just under the sticky nav. Back/forward goes through the hash listener instead, so the browser's
  // own scroll restoration applies.
  const scrollPanelToTop = () => {
    const panel = panelRef.current;
    const navHeight = document.getElementById('dashboard-nav')?.getBoundingClientRect().height ?? 0;
    const panelTop = panel?.getBoundingClientRect().top;
    if (panelTop !== undefined && panelTop < navHeight) {
      const reduce = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
      window.scrollTo({ top: window.scrollY + panelTop - navHeight, behavior: reduce ? 'auto' : 'smooth' });
    }
  };
  const onSelectTab = (tab: TabKey) => {
    scrollPanelToTop();
    selectTab(tab);
  };
  const goToDealsFromTab = (filters?: DealFilters) => {
    scrollPanelToTop();
    goToDeals(filters);
  };

  const renderTab = () => {
    switch (view.tab) {
      case 'overview':
        // OverviewTab wraps each of its sections in its own ErrorBoundary.
        return (
          <OverviewTab
            deals={regionDeals}
            allDeals={allData.risks ?? []}
            region={view.region}
            briefing={{ briefing: executiveBriefing, fallbackBriefing, totalOpportunities, period: dataAsOf, isLive }}
            delta={deltaIntelligence}
            dealsError={dealsError}
            onGoToDeals={goToDealsFromTab}
            onSelectRegion={selectRegion}
            onSeeChanges={() => onSelectTab('comp')}
          />
        );
      case 'cro':
        // CroBriefTab wraps each of its sections in its own ErrorBoundary.
        return <CroBriefTab twentyQuestions={twentyQuestions} recommendations={data.recommendations} region={view.region} deals={regionDeals} dealsError={dealsError} isLive={isLive} />;
      case 'deals':
        return <DealsTab deals={regionDeals} region={view.region} filters={view} onFiltersChange={setFilters} dealsError={dealsError} />;
      case 'health':
        // PipelineHealthTab wraps each of its panels in its own ErrorBoundary.
        return (
          <PipelineHealthTab
            deals={regionDeals}
            funnel={data.funnel}
            forecastStat={data.stats.forecast}
            region={view.region}
            dealsError={dealsError}
            onGoToDeals={goToDealsFromTab}
          />
        );
      case 'comp':
        // CompetitionTab wraps each of its sections in its own ErrorBoundary.
        return <CompetitionTab delta={deltaIntelligence} displacement={competitiveDisplacement} twentyQuestions={twentyQuestions} region={view.region} isLive={isLive} />;
    }
  };

  return (
    <MotionConfig reducedMotion="user">
      <ReviewsContext.Provider value={reviews}>
        <div style={{ maxWidth: 1920, margin: '0 auto', padding: '0 clamp(1rem, 3vw, 2rem)' }}>
          {/* The visible PRISM wordmark is styled text; this gives the page its one h1. */}
          <h1 style={visuallyHidden}>Prism revenue intelligence</h1>
          <Header onUploadClick={() => setUploadOpen(true)} period={dataAsOf} nextRefresh={isLive ? nextRefresh : undefined} isLive={isLive} generatedAt={reportCreatedAt ?? reportDate} />
          <UploadModal isOpen={uploadOpen} onClose={() => setUploadOpen(false)} />
          <PrismBar style={{ marginBottom: '1rem' }} />

          {loading && !showingContent && (
            <div style={{ display: 'flex', justifyContent: 'center', padding: '6rem 2rem', fontFamily: 'var(--font-mono)', fontSize: '0.85rem', color: 'var(--text-muted)' }}>
              Loading…
            </div>
          )}

          {!loading && !showingContent && (
            <div style={{
              display: 'flex',
              flexDirection: 'column',
              alignItems: 'center',
              justifyContent: 'center',
              padding: '6rem 2rem',
              textAlign: 'center',
              gap: '1.5rem',
            }}>
              <div style={{ fontSize: '3rem', opacity: 0.3 }}>◈</div>
              <div style={{ fontFamily: 'var(--font-display)', fontSize: '1.5rem', color: 'var(--text-primary)' }}>
                No live data yet
              </div>
              <div style={{ fontFamily: 'var(--font-mono)', fontSize: '0.85rem', color: 'var(--text-muted)', maxWidth: 420, lineHeight: 1.6 }}>
                Upload a Salesforce CSV export to run your first analysis. The intelligence engine will process your pipeline and populate this dashboard with live data.
              </div>
              <button
                onClick={() => setUploadOpen(true)}
                style={{
                  padding: '10px 28px',
                  fontSize: '0.85rem',
                  fontFamily: 'var(--font-mono)',
                  background: 'var(--accent)',
                  border: 'none',
                  borderRadius: 6,
                  color: '#fff',
                  cursor: 'pointer',
                  marginTop: '0.5rem',
                }}
              >
                Upload CSV →
              </button>
            </div>
          )}

          {showingContent && (
            <>
              <DashboardNav tab={view.tab} region={view.region} regionCounts={regionCounts} onSelectTab={onSelectTab} onSelectRegion={selectRegion} />
              {reviews.error && (
                <div role="alert" style={{ marginTop: '0.75rem', padding: '0.6rem 0.85rem', borderRadius: 6, border: '1px solid var(--warning)', background: 'var(--warning-subtle)', color: 'var(--warning-text)', fontSize: '0.8rem', display: 'flex', flexWrap: 'wrap', alignItems: 'center', justifyContent: 'space-between', gap: '0.5rem 1rem' }}>
                  {/* The hook's messages already say what failed ("Couldn't save the review: …"). */}
                  <span style={{ minWidth: 0, overflowWrap: 'anywhere' }}>{reviews.error}</span>
                  {reviews.clearError && (
                    <button type="button" onClick={() => reviews.clearError?.()} style={{ minHeight: 32, padding: '0 0.75rem', borderRadius: 6, border: '1px solid var(--warning)', background: 'transparent', color: 'var(--warning-text)', fontSize: '0.78rem', fontWeight: 600, cursor: 'pointer' }}>
                      Dismiss
                    </button>
                  )}
                </div>
              )}
              <main style={{ padding: '1.5rem 0 2rem' }}>
                <div ref={panelRef} id="dashboard-tabpanel" role="tabpanel" aria-labelledby={`tab-${view.tab}`} tabIndex={0}>
                  <motion.div key={view.tab} variants={containerVariants} initial="hidden" animate="visible">
                    {/* Each tab, and each widget in it, sits behind an ErrorBoundary so one bad payload never blanks the dashboard.
                        Keyed on region too: a region change remounts the tab, clearing widget-local filters and any crash. */}
                    <ErrorBoundary key={`${view.tab}:${view.region}`} section={tabLabel}>{renderTab()}</ErrorBoundary>
                  </motion.div>
                </div>
              </main>
              <ErrorBoundary section="Processing Footer">
                <ProcessingFooter {...reportMeta} />
              </ErrorBoundary>
            </>
          )}
        </div>
      </ReviewsContext.Provider>
    </MotionConfig>
  );
}
